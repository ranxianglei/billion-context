import { test } from "node:test";
import assert from "node:assert/strict";
import { consumeHostIdChannel, countToolUnits, HOSTID_BODY_FIELD, HOSTID_MAX_UNITS } from "../src/hostid-channel.js";

const MARKER = { pluginMarker: true };
const NO_MARKER = { pluginMarker: false };

function openaiBody(): Record<string, unknown> {
    return {
        model: "gpt-test",
        messages: [
            { role: "system", content: "sys" },
            { role: "user", content: "hi" },
            { role: "assistant", content: null, tool_calls: [
                { id: "c1", type: "function", function: { name: "Bash", arguments: '{"cmd":"ls"}' } },
                { id: "c2", type: "function", function: { name: "Read", arguments: '{"path":"a"}' } },
            ] },
            { role: "tool", tool_call_id: "c1", content: "out1" },
            { role: "tool", tool_call_id: "c2", content: "out2" },
            { role: "assistant", content: "done" },
        ],
    };
}

function anthropicBody(): Record<string, unknown> {
    return {
        model: "claude-test",
        messages: [
            { role: "user", content: "hi" },
            { role: "assistant", content: [
                { type: "tool_use", id: "c1", name: "Bash", input: { cmd: "ls" } },
                { type: "tool_use", id: "c2", name: "Read", input: { path: "a" } },
            ] },
            { role: "user", content: [
                { type: "tool_result", tool_use_id: "c1", content: "out1" },
                { type: "tool_result", tool_use_id: "c2", content: "out2" },
            ] },
            { role: "assistant", content: [{ type: "text", text: "done" }] },
        ],
    };
}

function responsesBody(): Record<string, unknown> {
    return {
        model: "gpt-test",
        input: [
            { type: "message", role: "user", content: "hi" },
            { type: "message", role: "assistant", content: "thinking" },
            { type: "function_call", call_id: "c1", name: "Bash", arguments: '{"cmd":"ls"}' },
            { type: "function_call", call_id: "c2", name: "Read", arguments: '{"path":"a"}' },
            { type: "function_call_output", call_id: "c1", output: "out1" },
            { type: "function_call_output", call_id: "c2", output: "out2" },
        ],
    };
}

function googleBody(): Record<string, unknown> {
    return {
        contents: [
            { role: "user", parts: [{ text: "hi" }] },
            { role: "model", parts: [{ text: "ok" }, { functionCall: { name: "Bash", args: { cmd: "ls" } } }, { functionCall: { name: "Read", args: { path: "a" } } }] },
            { role: "user", parts: [{ functionResponse: { name: "Bash", response: { output: "out1" } } }] },
            { role: "user", parts: [{ functionResponse: { name: "Read", response: { output: "out2" } } }] },
        ],
    };
}

test("countToolUnits: openai (2 calls + 2 results = 4)", () => {
    const b = openaiBody();
    assert.equal(countToolUnits(b.messages as unknown[]), 4);
});

test("countToolUnits: anthropic (multi-block tool_result message splits per block)", () => {
    const b = anthropicBody();
    assert.equal(countToolUnits(b.messages as unknown[]), 4);
});

test("countToolUnits: responses (function_call items merge into assistant run, outputs are tool turns)", () => {
    const b = responsesBody();
    assert.equal(countToolUnits(b.input as unknown[]), 4);
});

test("countToolUnits: google (functionCall parts + one functionResponse turn per item)", () => {
    const b = googleBody();
    assert.equal(countToolUnits(b.contents as unknown[]), 4);
});

test("countToolUnits: leading system run and text turns carry no units", () => {
    const msgs = [
        { role: "system", content: "harness state" },
        { role: "user", content: "[model changed: assistant turns above this point were generated by x; the session continues with y]" },
        { role: "user", content: "plain" },
        { role: "assistant", content: "plain too" },
    ];
    assert.equal(countToolUnits(msgs), 0);
});

test("consume: absent field ⇒ decision untouched (both with and without marker)", () => {
    for (const opts of [MARKER, NO_MARKER]) {
        const b = openaiBody();
        const d = consumeHostIdChannel(b, { ...opts, protocol: "openai" });
        assert.deepEqual(d, { stripped: false });
        assert.ok(!(HOSTID_BODY_FIELD in b), "field must not be invented");
    }
});

test("consume: no marker ⇒ still stripped (reserved namespace) but never consumed", () => {
    const b = openaiBody();
    b[HOSTID_BODY_FIELD] = ["a", "b", "c", "d"];
    const d = consumeHostIdChannel(b, { ...NO_MARKER, protocol: "openai" });
    assert.equal(d.stripped, true, "unmarked value must not ride upstream on any prepare path");
    assert.equal(d.rejected, "no-marker");
    assert.equal(d.list, undefined);
    assert.ok(!(HOSTID_BODY_FIELD in b));
});

test("consume: valid list under marker ⇒ consumed + key removed", () => {
    const b = openaiBody();
    const ids = ["u-1", "u-2", "u-3", "u-4"];
    b[HOSTID_BODY_FIELD] = ids;
    const d = consumeHostIdChannel(b, { ...MARKER, protocol: "openai" });
    assert.equal(d.stripped, true);
    assert.equal(d.rejected, undefined);
    assert.deepEqual(d.list, ids);
    assert.ok(!(HOSTID_BODY_FIELD in b));
});

test("consume: empty list is well-formed only when the body has zero units", () => {
    const toolless: Record<string, unknown> = { model: "m", messages: [{ role: "user", content: "hi" }] };
    toolless[HOSTID_BODY_FIELD] = [];
    assert.deepEqual(consumeHostIdChannel(toolless, { ...MARKER, protocol: "openai" }), { stripped: true, list: [] });

    const b = openaiBody();
    b[HOSTID_BODY_FIELD] = [];
    assert.equal(consumeHostIdChannel(b, { ...MARKER, protocol: "openai" }).rejected, "miscount");
});

for (const wire of ["openai", "anthropic", "responses", "google"] as const) {
    test(`consume: ${wire} — all four wires accept their own shape`, () => {
        const bodies: Record<typeof wire, () => Record<string, unknown>> = {
            openai: openaiBody, anthropic: anthropicBody, responses: responsesBody, google: googleBody,
        };
        const b = bodies[wire]();
        b[HOSTID_BODY_FIELD] = ["u-1", "u-2", "u-3", "u-4"];
        const d = consumeHostIdChannel(b, { ...MARKER, protocol: wire });
        assert.equal(d.stripped, true, `${wire}: expected consumption`);
        assert.equal(d.rejected, undefined, `${wire}: rejected=${d.rejected}`);
        assert.equal(d.list?.length, 4);
        assert.ok(!(HOSTID_BODY_FIELD in b));
    });
}

test("consume: malformed shapes are rejected AND still removed", () => {
    // ([] is well-formed and covered by the dedicated empty-list case.)
    const cases: unknown[] = ["nope", 42, null, { a: 1 }, ["ok", 7], ["", "x"], [null]];
    for (const raw of cases) {
        const b = openaiBody();
        b[HOSTID_BODY_FIELD] = raw;
        const d = consumeHostIdChannel(b, { ...MARKER, protocol: "openai" });
        assert.equal(d.stripped, true, `raw=${JSON.stringify(raw)} must be stripped`);
        assert.equal(d.rejected, "malformed");
        assert.ok(!(HOSTID_BODY_FIELD in b), "malformed value must not survive to upstream");
    }
});

test("consume: over-cap list is rejected and removed", () => {
    const b = openaiBody();
    b[HOSTID_BODY_FIELD] = Array.from({ length: HOSTID_MAX_UNITS + 1 }, (_, i) => `id-${i}`);
    const d = consumeHostIdChannel(b, { ...MARKER, protocol: "openai" });
    assert.equal(d.rejected, "malformed");
    assert.ok(!(HOSTID_BODY_FIELD in b));
});

test("consume: miscount (length ≠ counted units) is rejected and removed", () => {
    for (const len of [0, 3, 5, 99]) {
        const b = openaiBody();
        b[HOSTID_BODY_FIELD] = Array.from({ length: len }, (_, i) => `id-${i}`);
        const d = consumeHostIdChannel(b, { ...MARKER, protocol: "openai" });
        assert.equal(d.stripped, true);
        assert.equal(d.rejected, "miscount", `len=${len}`);
        assert.ok(!(HOSTID_BODY_FIELD in b));
    }
});

test("consume: responses/google read their own arrays (messages key is not theirs)", () => {
    const r = responsesBody();
    r[HOSTID_BODY_FIELD] = ["u-1", "u-2", "u-3", "u-4"];
    assert.equal(consumeHostIdChannel(r, { ...MARKER, protocol: "responses" }).rejected, undefined);

    // a responses-shaped body whose ONLY array is `messages` has no recognizable input
    const stray: Record<string, unknown> = { model: "m", messages: [{ role: "user", content: "x" }] };
    stray[HOSTID_BODY_FIELD] = ["u-1"];
    const d = consumeHostIdChannel(stray, { ...MARKER, protocol: "responses" });
    assert.equal(d.rejected, "miscount", "unrecognizable message array ⇒ never trusted unchecked");
    assert.ok(!(HOSTID_BODY_FIELD in stray));
});
